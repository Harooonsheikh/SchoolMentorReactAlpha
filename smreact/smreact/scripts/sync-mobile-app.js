/* Sandbox Mobile App — public/downloads/ me jo bhi .apk ho, uska naam generated
   config me likh deta hai. Agar folder me ek se zyada APK hon to sab se naya
   (modified time ke hisaab se) chuna jata hai.

   Chalane ka tareeqa:  node scripts/sync-mobile-app.js
   (APK badlo to ye dobara chalao, phir build karo.) */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'public', 'downloads');
const out = path.join(root, 'src', 'erp', 'config', 'mobileAppDownload.generated.js');

let fileName = null;
if (fs.existsSync(dir)) {
  const apks = fs.readdirSync(dir)
    .filter((f) => f.toLowerCase().endsWith('.apk'))
    .map((f) => ({ f, t: fs.statSync(path.join(dir, f)).mtimeMs }))
    .sort((a, b) => b.t - a.t);
  if (apks.length) fileName = apks[0].f;
}

fs.writeFileSync(
  out,
  '// AUTO-GENERATED by scripts/sync-mobile-app.js — edit nahi karna.\n'
  + `export const MOBILE_APP_FILE_NAME = ${JSON.stringify(fileName)};\n`,
);
console.log(fileName
  ? `Mobile app: ${fileName}`
  : 'Mobile app: no .apk found in public/downloads/');
